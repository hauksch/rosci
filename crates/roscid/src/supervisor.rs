//! Keeps one warm `OsciClient` for the process lifetime.
//!
//! With the native stack there is no child process to outlive and no
//! dialog state worth resetting between requests — every operation runs
//! its own OSCI dialog — so "supervision" has narrowed to building the
//! client once, lazily, and handing it out.

use osci::{Error, OsciClient};

use crate::server::RequestError;

type Build = Box<dyn Fn() -> Result<OsciClient, Error> + Send>;

pub struct Supervisor {
    build: Build,
    client: Option<OsciClient>,
}

impl Supervisor {
    pub fn new(build: impl Fn() -> Result<OsciClient, Error> + Send + 'static) -> Self {
        Self {
            build: Box::new(build),
            client: None,
        }
    }

    /// Runs `op` against the warm client, building it on first use.
    /// Configuration failures surface on every request until they are
    /// fixed — a daemon with a broken keystore must say so, not loop.
    pub fn with_client<T>(
        &mut self,
        mut op: impl FnMut(&mut OsciClient) -> Result<T, RequestError>,
    ) -> Result<T, RequestError> {
        if self.client.is_none() {
            self.client = Some((self.build)()?);
        }
        op(self.client.as_mut().unwrap())
    }

    /// No process to stop natively; kept for the shutdown dance's shape.
    pub fn shutdown(&mut self) {
        if let Some(mut client) = self.client.take() {
            let _ = client.shutdown();
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::server::RequestError;

    #[test]
    fn build_failure_surfaces_instead_of_looping() {
        let mut supervisor =
            Supervisor::new(|| Err(osci::Error::Config("no keystore for you".into())));
        let err = supervisor
            .with_client(|c| {
                c.versions()
                    .map(|_| ())
                    .map_err(|err| RequestError::from_library("test", &err))
            })
            .unwrap_err();
        assert!(
            err.message.contains("no keystore"),
            "build failures must surface, not loop: {err:?}"
        );
    }

    #[test]
    fn the_client_is_built_once_and_reused() {
        use std::sync::Arc;
        use std::sync::atomic::{AtomicU32, Ordering};

        // A keystore built from generated bytes fails to parse — that is
        // enough to count builds without any network.
        let builds = Arc::new(AtomicU32::new(0));
        let counter = builds.clone();
        let mut supervisor = Supervisor::new(move || {
            counter.fetch_add(1, Ordering::SeqCst);
            Err(osci::Error::Config("counted".into()))
        });
        for _ in 0..3 {
            let _ = supervisor.with_client(|_| -> Result<(), RequestError> { Ok(()) });
        }
        assert_eq!(
            builds.load(Ordering::SeqCst),
            3,
            "each request retries the build while it fails"
        );
    }
}
